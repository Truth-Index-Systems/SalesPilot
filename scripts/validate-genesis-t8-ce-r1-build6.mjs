import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const read = (p) => fs.readFileSync(path.join(root, p), "utf8");
const contract = read("lib/genesis-t8/ai-research-contract.ts");
const ontology = read("lib/genesis-t8/commercial-genome-ontology.ts");
const index = read("lib/genesis-t8/index.ts");
const pkg = JSON.parse(read("package.json"));

const checks = [];
const check = (name, ok) => checks.push({ name, ok: Boolean(ok) });
const has = (s) => contract.includes(s);

check("Build 6 contract module exists", fs.existsSync(path.join(root, "lib/genesis-t8/ai-research-contract.ts")));
check("Build 6 version is fenced", has('GENESIS_T8_AI_RESEARCH_CONTRACT_VERSION = "1.0.0"'));
check("Build 6 identifier is unique", has('GENESIS_T8_CE_AI_RESEARCH_CONTRACT_BUILD = "BUILD6"'));
check("Provider-neutral schema is versioned", has('genesis_t8_commercial_research_v1'));
check("Contract imports canonical genome ontology", has('from "./commercial-genome-ontology"'));
check("Contract imports token theory", has('from "./token-theory"'));
check("Contract imports 9D graph", has('from "./commercial-graph-9d"'));
check("AI restricted to canonical predicates", has("AI_RESEARCHES_ONLY_CANONICAL_GENOME_PREDICATES"));
check("AI output remains candidate knowledge", has("AI_OUTPUT_IS_CANDIDATE_KNOWLEDGE_NOT_AUTHORITATIVE_KNOWLEDGE"));
check("Every assertion requires evidence", has("EVERY_ASSERTED_CANDIDATE_REQUIRES_EVIDENCE"));
check("Exact atomic evidence rule exists", has("EVIDENCE_MUST_SUPPORT_THE_EXACT_ATOMIC_ASSERTION"));
check("AI truth assignment is forbidden", has("AI_MAY_EXTRACT_AND_CANONICALISE_BUT_MAY_NOT_ASSIGN_TRUTH"));
check("Probability/confidence/coverage forbidden", has("AI_MAY_NOT_OUTPUT_PROBABILITY_CONFIDENCE_COVERAGE_OR_TI_FIELDS"));
check("Commercial scoring fields forbidden", has("AI_MAY_NOT_OUTPUT_MATCH_FIT_PRIORITY_OPPORTUNITY_OR_RECOMMENDATION"));
check("Missing knowledge is not false", has("AI_MAY_NOT_TREAT_MISSING_KNOWLEDGE_AS_FALSE"));
check("Not-found and contradiction are distinct", has("AI_MUST_DISTINGUISH_NOT_FOUND_FROM_CONTRADICTED"));
check("Ambiguity must be surfaced", has("AI_MUST_EXPOSE_AMBIGUITY_RATHER_THAN_RESOLVE_IT_BY_GUESSING"));
check("Conflicting candidates may coexist", has("CONFLICTING_CANDIDATES_MAY_COEXIST_FOR_TI_2_1_8_TO_RESOLVE"));
check("TI remains sole truth authority", has("TI_2_1_8_IS_THE_SOLE_AUTHORITY_FOR_TRUTH_QUALIFICATION"));
check("Hard validation precedes TI", has("DETERMINISTIC_CODE_HARD_VALIDATES_BEFORE_TI_QUALIFICATION"));
check("Research completion does not imply omniscience", has("RESEARCH_COMPLETION_DOES_NOT_MEAN_ALL_PREDICATES_ARE_KNOWN"));
check("Evidence envelope carries source URL", has("sourceUrl: string"));
check("Evidence envelope carries source class", has("sourceClass: GenesisT8ResearchSourceClass"));
check("Evidence envelope carries observation time", has("observedAt: string"));
check("Evidence envelope carries exact excerpt", has("excerpt: string"));
check("Evidence roles include contradiction", has('"CONTRADICTING"'));
check("Candidate disposition includes NOT_FOUND", has('"NOT_FOUND"'));
check("Candidate disposition includes AMBIGUOUS", has('"AMBIGUOUS"'));
check("Candidate references evidence IDs", has("evidenceIds: readonly string[]"));
check("Candidate cannot propose TRUTH dimension by type", has('Exclude<GenesisT8CommercialDimension, "TRUTH">'));
check("Relationships remain candidate objects", has("GenesisT8AIResearchCandidateRelation"));
check("Predicate result can say NOT_RESEARCHED", has('"NOT_RESEARCHED"'));
check("Directives derive from ontology", has("buildAIResearchDirectives"));
check("Unknown predicates hard fail", has("GENESIS_T8_AI_RESEARCH_VIOLATION:UNKNOWN_PREDICATE"));
check("Assertion value is mandatory", has("ASSERTION_VALUE_REQUIRED"));
check("Assertion evidence is mandatory", has("ASSERTION_EVIDENCE_REQUIRED"));
check("NOT_FOUND cannot assert value", has("NOT_FOUND_MUST_NOT_ASSERT_VALUE"));
check("AMBIGUOUS requires note", has("AMBIGUITY_NOTE_REQUIRED"));
check("Unrequested predicates are forbidden", has("UNREQUESTED_PREDICATE"));
check("Candidate evidence must exist", has("CANDIDATE_EVIDENCE_MISSING"));
check("Relationship evidence must exist", has("RELATION_EVIDENCE_REQUIRED"));
check("Every requested predicate needs a result", has("EVERY_REQUESTED_PREDICATE_NEEDS_RESULT"));
check("Forbidden inference key guard exists", has("assertNoForbiddenInferenceKeys"));
check("Candidate-to-token adapter stays DISCOVERED", has('lifecycle: "DISCOVERED" as const'));
check("Candidate-to-token adapter attaches no truth", !/candidateToDiscoveredToken[\s\S]*truth\s*:/.test(contract));
check("Candidate-to-token adapter records AI provenance", has('discoveredBy: "AI" as const'));
check("Build 6 is publicly exported", index.includes('export * from "./ai-research-contract";'));
check("Build 6 npm validation hook exists", Boolean(pkg.scripts?.["genesis:t8-ce-r1-build6-check"]));
check("Build 6 hook chains Build 5", String(pkg.scripts?.["genesis:t8-ce-r1-build6-check"] ?? "").includes("genesis:t8-ce-r1-build5-check"));
check("Ontology remains free of authoritative fit predicate", !/predicate:\s*["'][^"']*(match_score|fit_score|opportunity_score|priority_score)/i.test(ontology));

const failed = checks.filter((c) => !c.ok);
for (const c of checks) console.log(`${c.ok ? "PASS" : "FAIL"}  ${c.name}`);
console.log(`\nGenesis T8 CE-R1 Build 6: ${checks.length - failed.length}/${checks.length} checks passed.`);
if (failed.length) process.exit(1);
