import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd();
const read=(p)=>fs.readFileSync(path.join(root,p),'utf8');
const checks=[];
const check=(name,ok)=>{checks.push([name,!!ok]); if(!ok) console.error(`FAIL: ${name}`)};
const constants=read('lib/genesis-g8/truth-v2/evidence/constants.ts');
const quality=read('lib/genesis-g8/truth-v2/evidence/quality.ts');
const fresh=read('lib/genesis-g8/truth-v2/evidence/freshness.ts');
const indep=read('lib/genesis-g8/truth-v2/evidence/independence.ts');
const strength=read('lib/genesis-g8/truth-v2/evidence/strength.ts');
const b1=read('supabase/migrations/0128_genesis_g82_mrti2_build1_foundation.sql');
check('SD penalty frozen at 0.5',/MR_TI_2_EVIDENCE_SD_PENALTY\s*=\s*0\.5/.test(constants));
check('lineage decay base frozen at 3',/MR_TI_2_LINEAGE_DECAY_BASE\s*=\s*3/.test(constants));
check('quality uses weighted mean',/weightedMean/.test(quality));
check('quality uses weighted standard deviation',/weightedStandardDeviation/.test(quality));
check('quality subtracts SD penalty',/weightedMean-\(MR_TI_2_EVIDENCE_SD_PENALTY\*weightedStandardDeviation\)/.test(quality));
check('freshness uses exponential half-life',/2\*\*\(-ageDays\/halfLifeDays\)/.test(fresh));
check('independence uses exponential lineage depth',/MR_TI_2_LINEAGE_DECAY_BASE\*\*\(-derivativeDepth\)/.test(indep));
check('effective strength is Q x F x I',/quality\.intrinsicQuality\*freshnessModifier\*independenceModifier/.test(strength));
check('effective strength capped at 0.999',/MR_TI_2_PROBABILITY_CAP/.test(strength));
check('Build 1 stores primitive evidence only',/Derived MR-TI-2 maths is not stored here/.test(b1));
check('no TI-1 maths imported into evidence layer',![quality,fresh,indep,strength].some(s=>/critical_claim_ceiling|truth\/equation|truth\/review|MR-TI-1/.test(s)));
check('truth-v2 exports evidence engine',/export \* from "\.\/evidence"/.test(read('lib/genesis-g8/truth-v2/index.ts')));
check('math test script exists',fs.existsSync(path.join(root,'scripts/test-mr-ti2-build3-math.mjs')));
const failed=checks.filter(([,ok])=>!ok);
console.log(`MR-TI-2 Build 3 structural validator: ${checks.length-failed.length}/${checks.length} passed`);
if(failed.length) process.exit(1);
