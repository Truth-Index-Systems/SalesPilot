const EPS=1e-9;
const approx=(a,b,t=1e-9)=>Math.abs(a-b)<=t;
const cap=.999;
const pct=x=>Math.min(99.9,Math.max(0,x*100));
const mf=fi=>Math.max(0,Math.min(1,1-(1-Math.max(0,Math.min(1,fi)))**1.5));
const aggregate=(defs,claims)=>{
  const eligible=defs.filter(d=>d.coverage!==false);
  const total=eligible.reduce((s,d)=>s+d.w,0);
  const represented=eligible.filter(d=>claims[d.k]!==null&&claims[d.k]!==undefined);
  const rw=represented.reduce((s,d)=>s+d.w,0);
  const mass=represented.reduce((s,d)=>s+d.w*claims[d.k],0);
  const coverage=rw/total,rc=rw?mass/rw:0,base=mass/total;
  const fs=defs.filter(d=>d.f&&claims[d.k]!==null&&claims[d.k]!==undefined);
  const fw=fs.reduce((s,d)=>s+d.w,0),fmass=fs.reduce((s,d)=>s+d.w*claims[d.k],0);
  const fi=fw?fmass/fw:1,mod=mf(fi),ti=Math.min(99.9,100*base*mod);
  return {coverage:coverage*100,rc:pct(rc),base:base*100,fi:pct(fi),mod,ti};
};
const checks=[]; const check=(name,ok)=>{checks.push([name,!!ok]);if(!ok)console.error('FAIL:',name)};
const defs=[{k:'identity',w:1,f:true},{k:'domain',w:.95,f:true},{k:'industry',w:.7},{k:'scale',w:.2}];
let r=aggregate(defs,{identity:.98,domain:.98,industry:.98,scale:.98});
check('full represented .98 yields 100 coverage',approx(r.coverage,100));
check('full represented .98 yields 98 represented confidence',approx(r.rc,98));
check('base truth equals weighted .98',approx(r.base,98));
check('strong foundations have near-one modifier',r.mod>.997);
check('truth remains below base only by foundational modifier',r.ti<98&&r.ti>97.7);
r=aggregate(defs,{identity:.99,domain:.99,industry:.99,scale:null});
check('missing low-weight scale lowers coverage modestly',r.coverage>92&&r.coverage<94);
check('missing low-weight scale keeps represented confidence 99',approx(r.rc,99));
r=aggregate(defs,{identity:null,domain:.98,industry:.98,scale:.98});
check('missing foundational identity lowers coverage',r.coverage<70);
check('missing foundational identity is excluded from FI rather than set false',approx(r.fi,98));
r=aggregate(defs,{identity:.35,domain:.98,industry:.98,scale:.98});
check('doubtful represented foundation materially lowers FI',r.fi<70);
check('doubtful represented foundation strongly penalises truth',r.ti<61);
r=aggregate(defs,{identity:null,domain:null,industry:.99,scale:null});
check('only one nonfoundation known retains high represented confidence',approx(r.rc,99));
check('only one nonfoundation known has low coverage',r.coverage<30);
r=aggregate(defs,{identity:null,domain:null,industry:null,scale:null});
check('all unknown gives zero coverage',approx(r.coverage,0));
check('all unknown gives zero represented confidence',approx(r.rc,0));
check('all unknown gives zero truth',approx(r.ti,0));
check('no represented foundations uses neutral modifier',approx(r.mod,1));
check('no represented foundations does not create truth without coverage',approx(r.ti,0));
check('FI curve .95 approximately .98882',approx(mf(.95),1-(.05**1.5),1e-12));
check('FI curve .80 approximately .91056',approx(mf(.8),1-(.2**1.5),1e-12));
check('FI curve .60 approximately .74702',approx(mf(.6),1-(.4**1.5),1e-12));
check('FI curve .35 approximately .47595',approx(mf(.35),1-(.65**1.5),1e-12));
const capDefs=[{k:'f',w:1,f:true}];
r=aggregate(capDefs,{f:cap});
check('represented confidence respects 99.9 cap',approx(r.rc,99.9));
check('final truth never exceeds 99.9',r.ti<=99.9);
const a=aggregate(defs,{identity:.9,domain:.9,industry:.9,scale:.9});
const b=aggregate(defs,{identity:.9,domain:.9,industry:.9,scale:null});
check('removing represented evidence cannot increase coverage',b.coverage<a.coverage);
check('base truth identity RC x coverage holds',approx(a.base,(a.rc/100)*(a.coverage/100)*100,1e-9));
const failed=checks.filter(([,ok])=>!ok); console.log(`MR-TI-2 Build 6 mathematical invariants: ${checks.length-failed.length}/${checks.length} passed`); if(failed.length)process.exit(1);
