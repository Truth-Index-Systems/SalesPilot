import fs from 'node:fs';
const checks=[]; const ok=(name,cond)=>{checks.push([name,!!cond]); if(!cond) console.error('FAIL',name)};
const read=(p)=>fs.readFileSync(p,'utf8');
const comp=read('lib/genesis-t8/cie/composition.ts');
const freeze=read('lib/genesis-t8/cie/freeze-candidate.ts');
const auto=read('lib/engagement/g5-autopilot.ts');
const sql=read('supabase/migrations/0146_genesis_t8_cie_r8_legacy_math_eradication.sql');
const structured=read('lib/contacts/structured-output.ts');
const aiRoute=read('lib/engagement/g5-channel-strategy-openai.ts');
const app=fs.readdirSync('app',{recursive:true}).filter(x=>typeof x==='string'&&x.endsWith('.tsx')).map(x=>read(`app/${x}`)).join('\n');
ok('freeze candidate declared',freeze.includes("FREEZE_CANDIDATE"));
ok('single authority assertion retained',freeze.includes('assertSingleAuthority'));
ok('contact weighted authority presentation only',comp.includes('CONTACT_WEIGHTED_AUTHORITY')&&comp.includes('currentMode: "PRESENTATION_ONLY"'));
ok('engagement confidence presentation only',comp.includes('G5_ENGAGEMENT_CONFIDENCE')&&comp.includes('currentMode: "PRESENTATION_ONLY"'));
ok('categorical autopilot authoritative',comp.includes('CIE_R8_AUTOPILOT_GATE')&&comp.includes('currentMode: "AUTHORITATIVE"'));
ok('typescript autopilot has no threshold env',!auto.includes('AUTOPILOT_ENGAGEMENT_CONFIDENCE_MIN')&&!auto.includes('p_min_engagement_confidence'));
ok('sql autopilot has no confidence comparison',!sql.match(/engagement_confidence\s*>?=/));
ok('sql requires CIE R4',sql.includes('cie_r4_commercial_decisions'));
ok('sql requires CIE R6',sql.includes('cie_r6_contact_decisions'));
ok('sql requires CIE R5 provenance',sql.includes("cie-r5-route-authority/v1"));
ok('channel truncation no longer sorted by routing score',!structured.includes('b.routingScore - a.routingScore'));
ok('legacy AI route selector fails closed',aiRoute.includes('CIE_R8_AUTHORITY_VIOLATION:AI_ROUTE_SELECTION_ERADICATED'));
ok('live app no opportunity score recommendation',!app.includes('opportunity_score')&&!app.includes('Opportunity Score')&&!app.includes('Opportunity score'));
const failed=checks.filter(([,v])=>!v); console.log(`CIE-R8 static ${checks.length-failed.length}/${checks.length}`); if(failed.length) process.exit(1);
