import assert from "node:assert/strict";
let passed=0;
const test=(name,fn)=>{fn();passed++;};
const clamp=x=>Math.min(1,Math.max(0,Number.isFinite(x)?x:0));
const profile=v=>[...v].map(clamp).sort((a,b)=>a-b);
const compare=(a,b)=>{a=profile(a);b=profile(b);for(let i=0;i<a.length;i++){if(a[i]>b[i]+1e-12)return 1;if(b[i]>a[i]+1e-12)return -1;}return 0;};
const floor=v=>Math.min(...profile(v));

test("weakest axis governs scalar floor",()=>assert.equal(floor([.2,.9,.9,.9]),.2));
test("strong axes cannot compensate",()=>assert.equal(floor([.2,1,1,1]),.2));
test("balanced strong beats uniform moderate",()=>assert.equal(compare([.75,.75,.75,.75],[.55,.55,.55,.55]),1));
test("leximin distinguishes same weakest margin",()=>assert.equal(compare([.2,.9,.9,.9],[.2,.25,.9,.9]),1));
test("second weakest governs after weakest tie",()=>assert.equal(compare([.2,.3,.9,.9],[.2,.4,.5,.9]),-1));
test("third weakest governs after first two tie",()=>assert.equal(compare([.2,.4,.5,.9],[.2,.4,.6,.7]),-1));
test("exact equal profiles tie",()=>assert.equal(compare([.2,.4,.6,.8],[.8,.6,.4,.2]),0));
test("dimension order invariant",()=>assert.deepEqual(profile([.8,.2,.6,.4]),profile([.4,.6,.8,.2])));
test("monotonic single-axis improvement cannot worsen",()=>assert.equal(compare([.2,.4,.6,.8],[.2,.5,.6,.8]),-1));
test("zero margin remains failure boundary",()=>assert.equal(floor([0,.9,.9,.9]),0));
test("unit ceiling deterministic",()=>assert.equal(floor([1.2,.9,.9,.9]),.9));
test("negative margin clamps to boundary",()=>assert.equal(floor([-.2,.9,.9,.9]),0));
test("NaN fails closed to zero",()=>assert.equal(floor([NaN,.9,.9,.9]),0));
test("no arithmetic mean preference",()=>{const a=[.2,.9,.9,.9],b=[.3,.3,.3,.3];assert.equal(compare(a,b),-1);});
test("multiple fragilities visible behind same floor",()=>assert.notDeepEqual(profile([.2,.9,.9,.9]),profile([.2,.25,.9,.9])));
test("lexicographic comparison is antisymmetric",()=>{const a=[.2,.9,.9,.9],b=[.2,.25,.9,.9];assert.equal(compare(a,b),-compare(b,a));});
test("lexicographic comparison transitive synthetic",()=>{const a=[.4,.5,.6,.7],b=[.3,.8,.8,.8],c=[.2,.9,.9,.9];assert.equal(compare(a,b),1);assert.equal(compare(b,c),1);assert.equal(compare(a,c),1);});
test("worst-case candidate ties when minimum ties",()=>assert.equal(floor([.2,.9,.9,.9]),floor([.2,.25,.9,.9])));
test("leximin resolves worst-case tie without weights",()=>assert.equal(compare([.2,.9,.9,.9],[.2,.25,.9,.9]),1));
test("viability candidate requires explicit disturbance model",()=>{const disturbance=undefined;assert.equal(disturbance,undefined);});
test("profile keeps complete noncompensatory fragility ordering",()=>assert.deepEqual(profile([.6,.1,.4,.8]),[.1,.4,.6,.8]));
