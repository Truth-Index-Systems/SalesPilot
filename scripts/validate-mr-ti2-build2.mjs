import fs from "node:fs";
import path from "node:path";
const root=process.cwd();
const read=(p)=>fs.readFileSync(path.join(root,p),"utf8");
const checks=[]; const check=(name,ok)=>{checks.push([name,Boolean(ok)]);};
const contracts=read("lib/genesis-g8/truth-v2/contracts.ts");
const types=read("lib/genesis-g8/truth-v2/types.ts");
const ai=read("lib/genesis-g8/truth-v2/ai/evidence-contract.ts");
const prompt=read("lib/genesis-g8/truth-v2/ai/prompt.ts");
const schema=read("lib/genesis-g8/truth-v2/ai/json-schema.ts");
const migration=read("supabase/migrations/0129_genesis_g82_mrti2_build2_contracts_ai_boundary.sql");
const profileSync=read("lib/genesis-g8/truth-v2/profile-sync.ts");

check("engine version is MR-TI-2.0",types.includes('MR_TI_2_ENGINE_VERSION = "MR-TI-2.0"'));
check("contract version isolated",types.includes('MR-TI-2-CONTRACTS-1.0'));
check("impact classes are V2 semantics",types.includes('"FOUNDATIONAL" | "COMMERCIAL" | "SUPPORTING" | "OPTIONAL"'));
check("all six entity contracts exist",["INDUSTRY","SECTOR","COMPANY","CONTACT","ROUTE","OPPORTUNITY"].every(k=>contracts.includes(`MR_TI_2_${k}_CONTRACT`)));
check("60 deterministic claim definitions",(contracts.match(/\bc\("/g)||[]).length===60);
check("contracts do not reference TI-1 criticality",!contracts.includes("criticality")&&!contracts.includes("ClaimCriticality"));
check("contracts include per-claim half life",contracts.includes("freshnessHalfLifeDays"));
check("contracts include V2 impact class",contracts.includes("impactClass"));
check("contracts allow Matrix 2 relationships",contracts.includes('"DEPENDS_ON", "CONTRADICTS"'));
check("AI contract returns primitive quality inputs",["authority","directness","traceability"].every(k=>ai.includes(k)));
check("AI contract returns freshness primitives",ai.includes("sourcePublishedAt")&&ai.includes("observedAt"));
check("AI contract returns lineage primitives",ai.includes("sourceLineageKey")&&ai.includes("derivativeDepth"));
check("AI contract returns relationship hints",ai.includes("relationshipHints")&&ai.includes("targetClaimKey"));
check("AI schema has no final Truth field",!["truthIndex","claimProbability","representedConfidence","foundationalIntegrity","freshnessModifier","independenceModifier"].some(k=>ai.includes(k)));
check("prompt forbids AI calculation",prompt.includes("You do NOT calculate Truth Index")&&prompt.includes("Missing evidence is UNKNOWN, never false"));
check("prompt explains score semantics",prompt.includes("AUTHORITY:")&&prompt.includes("DIRECTNESS:")&&prompt.includes("TRACEABILITY:"));
check("strict JSON schema exists",schema.includes("additionalProperties:false")&&schema.includes('enum:["MR-TI-2.0"]'));
check("migration is additive",!/(drop\s+table|drop\s+column|alter\s+table\s+public\.genesis_g8_intelligence_|update\s+public\.genesis_g8_intelligence_)/i.test(migration));
check("V2 contract catalogue exists",migration.includes("genesis_g8_truth_v2_contract_definitions"));
check("migration contains all 60 definitions",(migration.match(/^\s+\('(industry|sector|company|contact|route|opportunity)'/gm)||[]).length===60);
check("profile sync updates only V2 sidecar",migration.includes("sync_genesis_g8_truth_v2_claim_profiles")&&migration.includes("insert into public.genesis_g8_truth_v2_claim_profiles"));
check("profile sync helper is isolated",profileSync.includes("sync_genesis_g8_truth_v2_claim_profiles")&&!profileSync.includes("calculateTruthIndex"));

const activeRoots=["lib/genesis-g8/read-model.ts","lib/genesis-g8/autonomous-expansion-openai.ts","lib/genesis-g8/discovery-repair-openai.ts"];
check("active TI path not switched in Build 2",activeRoots.every(p=>!read(p).includes("truth-v2")));
const failed=checks.filter(([,ok])=>!ok);
for(const [name,ok] of checks) console.log(`${ok?"PASS":"FAIL"} ${name}`);
console.log(`\n${checks.length-failed.length}/${checks.length} checks passed`);
if(failed.length) process.exit(1);
